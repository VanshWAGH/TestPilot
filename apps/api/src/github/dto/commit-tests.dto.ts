import { ApiPropertyOptional } from "@nestjs/swagger";
import {
  IsArray,
  IsBoolean,
  IsOptional,
  IsString,
} from "class-validator";

export class CommitTestsDto {
  @ApiPropertyOptional({
    description: "Specific test file IDs to commit (commits all if omitted)",
    type: [String],
  })
  @IsOptional()
  @IsArray()
  @IsString({ each: true })
  testFileIds?: string[];

  @ApiPropertyOptional({
    description: "Only include approved test scenarios",
    default: true,
  })
  @IsOptional()
  @IsBoolean()
  onlyApproved?: boolean;

  @ApiPropertyOptional({
    description: "Target branch name. Defaults to generated/initial-tests or generated/crawl-<YYYYMMDD>",
  })
  @IsOptional()
  @IsString()
  branch?: string;

  @ApiPropertyOptional({
    description: "Custom Git commit message",
    default: "feat(tests): add automated Playwright test suite generated by TestPilot",
  })
  @IsOptional()
  @IsString()
  commitMessage?: string;

  @ApiPropertyOptional({
    description: "Whether to open a Pull Request on GitHub after committing",
    default: true,
  })
  @IsOptional()
  @IsBoolean()
  createPullRequest?: boolean;

  @ApiPropertyOptional({
    description: "Custom Pull Request title",
  })
  @IsOptional()
  @IsString()
  prTitle?: string;

  @ApiPropertyOptional({
    description: "Custom Pull Request body/description",
  })
  @IsOptional()
  @IsString()
  prBody?: string;

  @ApiPropertyOptional({
    description: "Include Page Object models in the commit",
    default: true,
  })
  @IsOptional()
  @IsBoolean()
  includePageObjects?: boolean;

  @ApiPropertyOptional({
    description: "Include test fixtures (auth state, helpers) in the commit",
    default: true,
  })
  @IsOptional()
  @IsBoolean()
  includeFixtures?: boolean;

  @ApiPropertyOptional({
    description: "Include playwright.config.ts in the commit",
    default: true,
  })
  @IsOptional()
  @IsBoolean()
  includeConfig?: boolean;
}

