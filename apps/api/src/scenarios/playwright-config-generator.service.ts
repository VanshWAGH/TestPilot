import { Injectable, Logger, NotFoundException } from "@nestjs/common";
import { PrismaService } from "../prisma/prisma.service";
import type { PlaywrightConfigResponse } from "@testpilot/shared";
import { GeneratePlaywrightConfigDto } from "./dto/generate-config.dto";
import * as ts from "typescript";

@Injectable()
export class PlaywrightConfigGeneratorService {
  private readonly logger = new Logger(PlaywrightConfigGeneratorService.name);

  constructor(private readonly prisma: PrismaService) {}

  /**
   * Generates a strongly typed playwright.config.ts for the target project.
   */
  async generateConfig(
    projectId: string,
    options?: GeneratePlaywrightConfigDto,
  ): Promise<PlaywrightConfigResponse> {
    const project = await this.prisma.project.findUnique({
      where: { id: projectId },
      include: {
        environments: {
          include: {
            credentials: true,
          },
        },
      },
    });

    if (!project) {
      throw new NotFoundException(`Project ${projectId} not found`);
    }

    const defaultEnv =
      project.environments.find((e) => e.isDefault) || project.environments[0];

    const baseUrl =
      options?.baseUrl || defaultEnv?.baseUrl || project.baseUrl || "http://localhost:3000";

    const hasCredentials = Boolean(
      defaultEnv?.credentials?.usernameEncrypted ||
        defaultEnv?.credentials?.loginUrl,
    );

    const hasAuthSetup =
      options?.enableAuthSetup !== undefined
        ? options.enableAuthSetup
        : hasCredentials || project.environments.length > 0;

    const timeout = options?.timeout ?? 30000;
    const expectTimeout = options?.expectTimeout ?? 5000;
    const captureTrace = options?.captureTrace ?? "retain-on-failure";
    const captureScreenshot = options?.captureScreenshot ?? "only-on-failure";
    const captureVideo = options?.captureVideo ?? "retain-on-failure";

    const browserKeys =
      options?.browsers && options.browsers.length > 0
        ? options.browsers
        : ["chromium", "firefox", "webkit"];

    const content = this.assembleConfigFile({
      projectName: project.name,
      baseUrl,
      timeout,
      expectTimeout,
      captureTrace,
      captureScreenshot,
      captureVideo,
      hasAuthSetup,
      browsers: browserKeys,
    });

    // Verify syntax with TypeScript compiler
    const { isValid, errors } = this.verifyTypeScript(
      content,
      "playwright.config.ts",
    );

    const reporters = [
      "html (playwright-report/)",
      "json (playwright-report/results.json)",
      "list",
      "github (in CI)",
    ];

    const activeProjectNames = [
      ...(hasAuthSetup ? ["setup"] : []),
      ...browserKeys,
    ];

    this.logger.log(
      `Generated Playwright config for project "${project.name}" (BaseURL: ${baseUrl}, Browsers: ${browserKeys.join(", ")}, Valid: ${isValid})`,
    );

    return {
      projectId,
      filePath: "playwright.config.ts",
      content,
      baseUrl,
      projects: activeProjectNames,
      reporters,
      hasAuthSetup,
      compilationStatus: isValid ? "valid" : "invalid",
      compilationErrors: errors,
    };
  }

  // ─── Code Assembly ──────────────────────────────────────────────────────────

  private assembleConfigFile(params: {
    projectName: string;
    baseUrl: string;
    timeout: number;
    expectTimeout: number;
    captureTrace: string;
    captureScreenshot: string;
    captureVideo: string;
    hasAuthSetup: boolean;
    browsers: string[];
  }): string {
    const lines: string[] = [];

    lines.push(`/**`);
    lines.push(` * TestPilot Automated Playwright Configuration`);
    lines.push(` * Project: ${params.projectName}`);
    lines.push(` * Base URL: ${params.baseUrl}`);
    lines.push(` * Auto-generated by TestPilot Engine`);
    lines.push(` */`);
    lines.push("");
    lines.push(`import { defineConfig, devices } from '@playwright/test';`);
    lines.push("");
    lines.push(`export default defineConfig({`);
    lines.push(`  testDir: './tests',`);
    lines.push(`  fullyParallel: true,`);
    lines.push(`  forbidOnly: !!process.env.CI,`);
    lines.push(`  retries: process.env.CI ? 2 : 0,`);
    lines.push(`  workers: process.env.CI ? 2 : undefined,`);
    lines.push(`  timeout: ${params.timeout},`);
    lines.push("");
    lines.push(`  expect: {`);
    lines.push(`    timeout: ${params.expectTimeout},`);
    lines.push(`  },`);
    lines.push("");
    lines.push(`  reporter: [`);
    lines.push(`    ['html', { open: 'never', outputFolder: 'playwright-report' }],`);
    lines.push(`    ['json', { outputFile: 'playwright-report/results.json' }],`);
    lines.push(`    ['list'],`);
    lines.push(`    ...(process.env.CI ? [['github'] as const] : []),`);
    lines.push(`  ],`);
    lines.push("");
    lines.push(`  use: {`);
    lines.push(`    baseURL: process.env.BASE_URL || '${this.escapeQuotes(params.baseUrl)}',`);
    lines.push(`    trace: '${params.captureTrace}',`);
    lines.push(`    screenshot: '${params.captureScreenshot}',`);
    lines.push(`    video: '${params.captureVideo}',`);
    lines.push(`    actionTimeout: 10_000,`);
    lines.push(`    navigationTimeout: 15_000,`);
    lines.push(`  },`);
    lines.push("");
    lines.push(`  projects: [`);

    // Auth setup project if enabled
    if (params.hasAuthSetup) {
      lines.push(`    // Setup project for pre-authenticating test sessions`);
      lines.push(`    {`);
      lines.push(`      name: 'setup',`);
      lines.push(`      testMatch: /.*\\.setup\\.ts/,`);
      lines.push(`    },`);
      lines.push("");
    }

    // Browsers
    for (const browser of params.browsers) {
      const lower = browser.toLowerCase();
      let deviceConfig = "...devices['Desktop Chrome']";
      let name = browser;

      if (lower.includes("firefox")) {
        deviceConfig = "...devices['Desktop Firefox']";
        name = "firefox";
      } else if (lower.includes("webkit") || lower.includes("safari")) {
        deviceConfig = "...devices['Desktop Safari']";
        name = "webkit";
      } else if (lower.includes("mobile-chrome") || lower.includes("pixel")) {
        deviceConfig = "...devices['Pixel 5']";
        name = "mobile-chrome";
      } else if (lower.includes("mobile-safari") || lower.includes("iphone")) {
        deviceConfig = "...devices['iPhone 12']";
        name = "mobile-safari";
      } else {
        deviceConfig = "...devices['Desktop Chrome']";
        name = "chromium";
      }

      lines.push(`    {`);
      lines.push(`      name: '${name}',`);
      lines.push(`      use: {`);
      lines.push(`        ${deviceConfig},`);
      if (params.hasAuthSetup) {
        lines.push(`        storageState: 'playwright/.auth/user.json',`);
      }
      lines.push(`      },`);
      if (params.hasAuthSetup) {
        lines.push(`      dependencies: ['setup'],`);
      }
      lines.push(`    },`);
    }

    lines.push(`  ],`);
    lines.push(`});`);
    lines.push("");

    return lines.join("\n");
  }

  // ─── Helpers ────────────────────────────────────────────────────────────────

  private escapeQuotes(str: string): string {
    return (str || "").replace(/'/g, "\\'");
  }

  private verifyTypeScript(
    code: string,
    fileName: string,
  ): { isValid: boolean; errors: string[] } {
    const result = ts.transpileModule(code, {
      compilerOptions: {
        module: ts.ModuleKind.ESNext,
        target: ts.ScriptTarget.ES2022,
        strict: false,
      },
      fileName,
      reportDiagnostics: true,
    });

    const errors: string[] = [];
    if (result.diagnostics && result.diagnostics.length > 0) {
      for (const diag of result.diagnostics) {
        if (diag.category === ts.DiagnosticCategory.Error) {
          const msg = ts.flattenDiagnosticMessageText(diag.messageText, "\n");
          errors.push(msg);
        }
      }
    }

    return {
      isValid: errors.length === 0,
      errors,
    };
  }
}
