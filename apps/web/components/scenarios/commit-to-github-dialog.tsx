"use client";

import { useState, useEffect } from "react";
import {
  GitPullRequest,
  GitBranch,
  FolderGit2,
  CheckCircle2,
  ExternalLink,
  Loader2,
  AlertCircle,
  FileCode2,
  Layers,
  Sparkles,
} from "lucide-react";
import {
  Dialog,
  DialogContent,
  DialogHeader,
  DialogTitle,
  DialogDescription,
} from "@/components/ui/dialog";
import { Button, buttonVariants } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Badge } from "@/components/ui/badge";
import Link from "next/link";
import { cn } from "cn";

interface CommitToGitHubDialogProps {
  projectId: string;
  projectName: string;
  open: boolean;
  onOpenChange: (open: boolean) => void;
  onCommitted?: () => void;
}

interface CommitResult {
  projectId: string;
  branch: string;
  commitSha: string;
  filesCommitted: string[];
  pullRequestUrl: string | null;
  pullRequestNumber: number | null;
  repoUrl: string;
}

interface GitHubStatus {
  isConfigured: boolean;
  connectedRepo: string | null;
  connectedBranch: string | null;
  installationId: string | null;
}

export function CommitToGitHubDialog({
  projectId,
  projectName,
  open,
  onOpenChange,
  onCommitted,
}: CommitToGitHubDialogProps) {
  const [status, setStatus] = useState<GitHubStatus | null>(null);
  const [isLoadingStatus, setIsLoadingStatus] = useState(false);
  const [isCommitting, setIsCommitting] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [result, setResult] = useState<CommitResult | null>(null);

  // Form fields
  const [branchName, setBranchName] = useState("");
  const [commitMessage, setCommitMessage] = useState(
    "feat(tests): add automated Playwright test suite generated by TestPilot",
  );
  const [createPullRequest, setCreatePullRequest] = useState(true);
  const [onlyApproved, setOnlyApproved] = useState(true);

  // Load project's GitHub integration status
  useEffect(() => {
    if (!open || !projectId) return;

    let isMounted = true;
    setIsLoadingStatus(true);
    setError(null);
    setResult(null);

    // Calculate default branch name
    const now = new Date();
    const yyyy = now.getFullYear();
    const mm = String(now.getMonth() + 1).padStart(2, "0");
    const dd = String(now.getDate()).padStart(2, "0");
    const defaultBranch = `generated/crawl-${yyyy}${mm}${dd}`;
    setBranchName(defaultBranch);

    fetch(`/api/github/projects/${projectId}/github/status`)
      .then((res) => {
        if (!res.ok) throw new Error(`HTTP ${res.status}`);
        return res.json();
      })
      .then((data) => {
        if (isMounted) {
          setStatus({
            isConfigured: data.isConfigured,
            connectedRepo: data.connectedRepo,
            connectedBranch: data.connectedBranch,
            installationId: data.installationId,
          });
        }
      })
      .catch((err) => {
        if (isMounted) {
          setError(
            err.message?.includes("404")
              ? "Project not found or GitHub integration not ready."
              : `Failed to load GitHub status: ${err.message}`,
          );
        }
      })
      .finally(() => {
        if (isMounted) setIsLoadingStatus(false);
      });

    return () => {
      isMounted = false;
    };
  }, [open, projectId]);

  const handleCommit = async () => {
    if (!projectId) return;
    setIsCommitting(true);
    setError(null);

    try {
      const res = await fetch(`/api/github/projects/${projectId}/github/commit`, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          branch: branchName.trim() || undefined,
          commitMessage: commitMessage.trim() || undefined,
          createPullRequest,
          onlyApproved,
        }),
      });

      const data = await res.json();
      if (!res.ok) {
        throw new Error(data.message || `Failed to commit (HTTP ${res.status})`);
      }

      setResult(data);
      onCommitted?.();
    } catch (err: any) {
      setError(err.message || "An unexpected error occurred during commit.");
    } finally {
      setIsCommitting(false);
    }
  };

  return (
    <Dialog open={open} onOpenChange={onOpenChange}>
      <DialogContent className="max-w-xl w-full p-6 bg-card border-border text-foreground">
        <DialogHeader className="space-y-1.5 pb-3 border-b border-border">
          <div className="flex items-center gap-2">
            <div className="p-1.5 rounded-md bg-primary/10 text-primary">
              <FolderGit2 className="w-5 h-5" />
            </div>
            <DialogTitle className="text-lg font-bold">
              Commit Test Suite to GitHub
            </DialogTitle>
          </div>
          <DialogDescription className="text-xs text-muted-foreground">
            Push approved Playwright tests, Page Object Models, fixtures, and configuration directly to your repository and open a Pull Request.
          </DialogDescription>
        </DialogHeader>

        {isLoadingStatus ? (
          <div className="py-12 flex flex-col items-center justify-center gap-3 text-muted-foreground">
            <Loader2 className="w-6 h-6 animate-spin text-primary" />
            <p className="text-xs">Checking repository connection...</p>
          </div>
        ) : status && !status.isConfigured ? (
          <div className="py-6 space-y-4">
            <div className="p-4 rounded-lg border border-amber-500/30 bg-amber-500/10 text-amber-200 space-y-2">
              <div className="flex items-center gap-2 font-medium text-sm">
                <AlertCircle className="w-4 h-4 text-amber-400" />
                <span>GitHub Repository Not Connected</span>
              </div>
              <p className="text-xs text-muted-foreground leading-relaxed">
                Project &quot;{projectName}&quot; is not yet linked to a GitHub test suite repository. Connect your GitHub App installation in Settings to enable automated commits and PRs.
              </p>
            </div>
            <div className="flex justify-end gap-2 pt-2">
              <Button
                variant="outline"
                size="sm"
                onClick={() => onOpenChange(false)}
              >
                Close
              </Button>
              <Link
                href="/settings"
                className={cn(
                  buttonVariants({ variant: "default", size: "sm" }),
                  "bg-primary text-primary-foreground hover:bg-primary/90",
                )}
              >
                Go to GitHub Settings
              </Link>
            </div>
          </div>
        ) : result ? (
          /* Success Screen */
          <div className="py-4 space-y-5">
            <div className="p-4 rounded-lg border border-emerald-500/30 bg-emerald-500/10 space-y-3">
              <div className="flex items-center gap-2 text-emerald-400 font-semibold text-sm">
                <CheckCircle2 className="w-5 h-5 text-emerald-400" />
                <span>Tests Successfully Committed &amp; Pushed!</span>
              </div>
              <p className="text-xs text-muted-foreground">
                Committed {result.filesCommitted?.length || 0} files to branch{" "}
                <code className="text-foreground font-mono bg-secondary/80 px-1 py-0.5 rounded">
                  {result.branch}
                </code>{" "}
                (commit{" "}
                <code className="text-foreground font-mono bg-secondary/80 px-1 py-0.5 rounded">
                  {result.commitSha.slice(0, 7)}
                </code>
                ).
              </p>
            </div>

            {/* Pull Request Card */}
            {result.pullRequestUrl && (
              <div className="p-4 rounded-lg border border-border bg-card/60 flex items-center justify-between gap-4">
                <div className="space-y-1">
                  <div className="flex items-center gap-2">
                    <GitPullRequest className="w-4 h-4 text-primary" />
                    <span className="text-sm font-medium">
                      Pull Request #{result.pullRequestNumber}
                    </span>
                    <Badge variant="outline" className="text-[10px] bg-primary/10 text-primary border-primary/20">
                      Open for Review
                    </Badge>
                  </div>
                  <p className="text-xs text-muted-foreground">
                    Review generated test code, verify assertions, and run CI checks.
                  </p>
                </div>
                <a
                  href={result.pullRequestUrl}
                  target="_blank"
                  rel="noopener noreferrer"
                  className={cn(
                    buttonVariants({ variant: "default", size: "sm" }),
                    "bg-primary hover:bg-primary/90 text-primary-foreground text-xs gap-1.5 h-8 shrink-0",
                  )}
                >
                  <span>View PR on GitHub</span>
                  <ExternalLink className="w-3.5 h-3.5" />
                </a>
              </div>
            )}

            {/* Committed Files Summary */}
            <div className="space-y-2">
              <span className="text-xs font-semibold text-muted-foreground uppercase tracking-wider">
                Artifacts Included ({result.filesCommitted?.length || 0})
              </span>
              <div className="max-h-36 overflow-y-auto space-y-1 rounded border border-border bg-background/50 p-2 text-xs font-mono">
                {result.filesCommitted.map((file) => (
                  <div key={file} className="flex items-center gap-2 text-muted-foreground">
                    <FileCode2 className="w-3.5 h-3.5 text-primary shrink-0" />
                    <span className="truncate">{file}</span>
                  </div>
                ))}
              </div>
            </div>

            <div className="flex justify-end pt-2">
              <Button
                variant="outline"
                size="sm"
                onClick={() => onOpenChange(false)}
              >
                Done
              </Button>
            </div>
          </div>
        ) : (
          /* Commit Configuration Form */
          <div className="py-4 space-y-4">
            {error && (
              <div className="p-3 rounded-lg border border-destructive/30 bg-destructive/10 text-destructive text-xs flex items-start gap-2">
                <AlertCircle className="w-4 h-4 mt-0.5 shrink-0" />
                <span>{error}</span>
              </div>
            )}

            {/* Target Repo Info */}
            <div className="p-3 rounded-lg border border-border bg-muted/40 flex items-center justify-between text-xs">
              <div className="flex items-center gap-2">
                <FolderGit2 className="w-4 h-4 text-muted-foreground" />
                <span className="text-muted-foreground">Target Repository:</span>
                <span className="font-semibold text-foreground font-mono">
                  {status?.connectedRepo}
                </span>
              </div>
              <Badge variant="outline" className="text-[10px]">
                Base: {status?.connectedBranch || "main"}
              </Badge>
            </div>

            {/* Branch Name Field */}
            <div className="space-y-1.5">
              <label className="text-xs font-medium flex items-center justify-between">
                <span className="flex items-center gap-1.5">
                  <GitBranch className="w-3.5 h-3.5 text-primary" />
                  Source Branch Name
                </span>
                <span className="text-[10px] text-muted-foreground">
                  (Strategy: initial-tests or crawl-&lt;date&gt;)
                </span>
              </label>
              <Input
                value={branchName}
                onChange={(e) => setBranchName(e.target.value)}
                placeholder="generated/crawl-20261110"
                className="h-8 text-xs font-mono"
              />
            </div>

            {/* Commit Message */}
            <div className="space-y-1.5">
              <label className="text-xs font-medium">Commit Message</label>
              <Input
                value={commitMessage}
                onChange={(e) => setCommitMessage(e.target.value)}
                placeholder="feat(tests): add automated Playwright test suite"
                className="h-8 text-xs"
              />
            </div>

            {/* Options */}
            <div className="pt-2 border-t border-border space-y-2.5">
              <label className="flex items-center gap-2.5 cursor-pointer text-xs">
                <input
                  type="checkbox"
                  checked={createPullRequest}
                  onChange={(e) => setCreatePullRequest(e.target.checked)}
                  className="rounded border-border accent-primary w-4 h-4"
                />
                <span className="font-medium text-foreground">
                  Open Pull Request automatically after commit
                </span>
              </label>

              <label className="flex items-center gap-2.5 cursor-pointer text-xs">
                <input
                  type="checkbox"
                  checked={onlyApproved}
                  onChange={(e) => setOnlyApproved(e.target.checked)}
                  className="rounded border-border accent-primary w-4 h-4"
                />
                <span className="font-medium text-foreground">
                  Only commit approved test scenarios
                </span>
              </label>
            </div>

            {/* Actions */}
            <div className="flex justify-end gap-2 pt-3 border-t border-border">
              <Button
                variant="outline"
                size="sm"
                onClick={() => onOpenChange(false)}
                disabled={isCommitting}
                className="text-xs h-8"
              >
                Cancel
              </Button>
              <Button
                size="sm"
                onClick={handleCommit}
                disabled={isCommitting || !branchName.trim()}
                className="text-xs h-8 bg-primary hover:bg-primary/90 text-primary-foreground gap-1.5"
              >
                {isCommitting ? (
                  <>
                    <Loader2 className="w-3.5 h-3.5 animate-spin" />
                    <span>Committing &amp; Creating PR...</span>
                  </>
                ) : (
                  <>
                    <GitPullRequest className="w-3.5 h-3.5" />
                    <span>Commit &amp; Open PR</span>
                  </>
                )}
              </Button>
            </div>
          </div>
        )}
      </DialogContent>
    </Dialog>
  );
}
