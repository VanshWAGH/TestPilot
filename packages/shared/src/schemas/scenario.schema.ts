import { z } from "zod";

export const ScenarioStatusSchema = z.enum(["draft", "approved", "rejected"]);
export type ScenarioStatus = z.infer<typeof ScenarioStatusSchema>;

export const ScenarioPrioritySchema = z.enum(["critical", "high", "medium", "low"]);
export type ScenarioPriority = z.infer<typeof ScenarioPrioritySchema>;

export const ScenarioStepSchema = z.object({
  stepNumber: z.number().int().positive(),
  action: z.enum([
    "navigate",
    "click",
    "fill",
    "select",
    "check",
    "assert_text",
    "assert_visible",
    "assert_url",
  ]),
  description: z.string(),
  locator: z.string().optional(),
  targetName: z.string().optional(),
  value: z.string().optional(),
  expected: z.string().optional(),
});
export type ScenarioStep = z.infer<typeof ScenarioStepSchema>;

export const ScenarioSchema = z.object({
  id: z.string().uuid(),
  projectId: z.string().uuid(),
  pageId: z.string().uuid().nullable().optional(),
  title: z.string().min(3),
  description: z.string(),
  priority: ScenarioPrioritySchema.default("medium"),
  status: ScenarioStatusSchema.default("draft"),
  steps: z.array(ScenarioStepSchema),
  userFlow: z.string().optional(),
  tags: z.array(z.string()).default([]),
  approvedBy: z.string().nullable().optional(),
  approvedAt: z.string().datetime().nullable().optional(),
  createdAt: z.string().datetime(),
  updatedAt: z.string().datetime(),
});
export type Scenario = z.infer<typeof ScenarioSchema>;

export const GenerateScenariosRequestSchema = z.object({
  projectId: z.string().uuid(),
  pageIds: z.array(z.string().uuid()).optional(),
  maxScenariosPerPage: z.number().int().min(1).max(10).default(3),
  focusAreas: z.array(z.string()).optional(),
});
export type GenerateScenariosRequest = z.infer<typeof GenerateScenariosRequestSchema>;

export const UpdateScenarioSchema = z.object({
  title: z.string().min(3).optional(),
  description: z.string().optional(),
  priority: ScenarioPrioritySchema.optional(),
  steps: z.array(ScenarioStepSchema).optional(),
  tags: z.array(z.string()).optional(),
});
export type UpdateScenarioInput = z.infer<typeof UpdateScenarioSchema>;

export const BatchApproveScenariosSchema = z.object({
  scenarioIds: z.array(z.string().uuid()).min(1),
  action: z.enum(["approve", "reject"]),
  reason: z.string().optional(),
});
export type BatchApproveScenariosInput = z.infer<typeof BatchApproveScenariosSchema>;

export const GenerateCodeRequestSchema = z.object({
  projectId: z.string().uuid(),
  scenarioIds: z.array(z.string().uuid()).min(1),
  outputFormat: z.enum(["playwright-ts", "playwright-js"]).default("playwright-ts"),
  pageObjectPattern: z.boolean().default(true),
});
export type GenerateCodeRequest = z.infer<typeof GenerateCodeRequestSchema>;

export const TestFileResponseSchema = z.object({
  id: z.string().uuid(),
  projectId: z.string().uuid(),
  filePath: z.string(),
  fileName: z.string(),
  content: z.string(),
  scenarioCount: z.number().int().nonnegative(),
  isCommitted: z.boolean().default(false),
  gitSha: z.string().nullable().optional(),
  createdAt: z.string().datetime(),
  updatedAt: z.string().datetime(),
});
export type TestFileResponse = z.infer<typeof TestFileResponseSchema>;

export const CommitTestsRequestSchema = z.object({
  projectId: z.string().uuid(),
  testFileIds: z.array(z.string().uuid()).min(1),
  commitMessage: z.string().min(5).default("test: add automated Playwright tests generated by TestPilot"),
  branch: z.string().default("testpilot/automated-tests"),
  createPullRequest: z.boolean().default(true),
});
export type CommitTestsRequest = z.infer<typeof CommitTestsRequestSchema>;

export const PageObjectResponseSchema = z.object({
  pageId: z.string(),
  className: z.string(),
  filePath: z.string(),
  content: z.string(),
  locatorsCount: z.number().int().nonnegative(),
  methodsCount: z.number().int().nonnegative(),
});
export type PageObjectResponse = z.infer<typeof PageObjectResponseSchema>;

export const GeneratedTestCodeArtifactSchema = z.object({
  id: z.string(),
  scenarioId: z.string(),
  scenarioTitle: z.string(),
  testFilePath: z.string(),
  testContent: z.string(),
  pageObjectPath: z.string().nullable().optional(),
  pageObjectContent: z.string().nullable().optional(),
  compilationStatus: z.enum(["valid", "invalid"]),
  compilationErrors: z.array(z.string()).default([]),
  fileContentHash: z.string(),
  createdAt: z.string().datetime(),
});
export type GeneratedTestCodeArtifact = z.infer<typeof GeneratedTestCodeArtifactSchema>;

export const PlaywrightFixtureResponseSchema = z.object({
  projectId: z.string(),
  fixtureFilePath: z.string(),
  fixtureContent: z.string(),
  authSetupFilePath: z.string().nullable().optional(),
  authSetupContent: z.string().nullable().optional(),
  pageObjectsIncluded: z.array(z.string()),
  hasAuthFixture: z.boolean(),
  hasTestDataFixture: z.boolean(),
  compilationStatus: z.enum(["valid", "invalid"]),
  compilationErrors: z.array(z.string()).default([]),
});
export type PlaywrightFixtureResponse = z.infer<typeof PlaywrightFixtureResponseSchema>;

export const PlaywrightConfigResponseSchema = z.object({
  projectId: z.string(),
  filePath: z.string(),
  content: z.string(),
  baseUrl: z.string(),
  projects: z.array(z.string()),
  reporters: z.array(z.string()),
  hasAuthSetup: z.boolean(),
  compilationStatus: z.enum(["valid", "invalid"]),
  compilationErrors: z.array(z.string()).default([]),
});
export type PlaywrightConfigResponse = z.infer<typeof PlaywrightConfigResponseSchema>;

export const TestSuiteBundleResponseSchema = z.object({
  projectId: z.string(),
  projectName: z.string(),
  baseUrl: z.string(),
  testFiles: z.array(GeneratedTestCodeArtifactSchema),
  pageObjects: z.array(PageObjectResponseSchema),
  fixtures: PlaywrightFixtureResponseSchema,
  config: PlaywrightConfigResponseSchema,
  totalFiles: z.number().int().nonnegative(),
});
export type TestSuiteBundleResponse = z.infer<typeof TestSuiteBundleResponseSchema>;

